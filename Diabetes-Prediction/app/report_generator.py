"""
report_generator.py
---------------------
Generates PDF reports using ReportLab:
    - generate_prediction_report(): a single-patient prediction result,
      formatted like a clinical summary sheet.
    - generate_history_report(): a tabular report of a user's full
      prediction history.

Kept separate from app/main.py (GUI) and app/predictor.py (inference) so
report formatting can change independently and be unit tested without
touching Tkinter.
"""

from __future__ import annotations

import io
import math
from datetime import datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # headless-safe backend, no display needed
import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import numpy as np
from PIL import Image as PILImage
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    Image as RLImage,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.utils import setup_logger
from app.validators import FEATURE_RANGES

logger = setup_logger("report_generator")

BRAND_COLOR = colors.HexColor("#0F766E")
RISK_COLOR_MAP = {
    "Green": colors.HexColor("#15803D"),
    "Yellow": colors.HexColor("#B45309"),
    "Red": colors.HexColor("#B91C1C"),
}
RISK_HEX = {"Green": "#15803D", "Yellow": "#B45309", "Red": "#B91C1C"}

DISCLAIMER = (
    "This report is generated by an educational machine-learning application "
    "and is not a medical diagnosis. Please consult a licensed healthcare "
    "professional for an accurate clinical assessment."
)


def _fig_to_flowable(fig, target_width: float) -> RLImage:
    """Save a matplotlib figure to an in-memory PNG and wrap it in a
    reportlab Image flowable, preserving the image's true aspect ratio
    (bbox_inches='tight' can change the saved aspect vs. the figsize)."""
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=150, bbox_inches="tight", transparent=True)
    plt.close(fig)
    buf.seek(0)

    with PILImage.open(buf) as pil_img:
        w, h = pil_img.size
    aspect = h / w
    buf.seek(0)

    return RLImage(buf, width=target_width, height=target_width * aspect)


def _fig_to_pil_image(fig) -> "PILImage.Image":
    """Save a matplotlib figure to an in-memory PNG and return it as a
    standalone PIL Image (fully loaded into memory, independent of the
    figure/buffer), for callers outside the PDF pipeline (e.g. a GUI
    preview) that need a plain image rather than a reportlab flowable."""
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=150, bbox_inches="tight", transparent=True)
    plt.close(fig)
    buf.seek(0)
    pil_img = PILImage.open(buf)
    pil_img.load()  # force full decode now, since the buffer goes out of scope
    return pil_img


def get_probability_gauge_image(probability: float, risk_level: str) -> "PILImage.Image":
    """Public helper: render the same probability gauge chart used in the
    PDF report as a standalone PIL Image, for GUI previews (e.g. a
    prediction details window) that don't need a full PDF."""
    fig = _plot_probability_gauge(probability, risk_level)
    return _fig_to_pil_image(fig)


def get_feature_profile_image(inputs: dict[str, float]) -> "PILImage.Image":
    """Public helper: render the same feature profile chart used in the
    PDF report as a standalone PIL Image, for GUI previews."""
    fig = _plot_feature_profile(inputs)
    return _fig_to_pil_image(fig)


def _plot_probability_gauge(probability: float, risk_level: str):
    """A semi-circular gauge showing the predicted diabetes probability,
    with color bands matching the Green/Yellow/Red risk thresholds."""
    fig, ax = plt.subplots(figsize=(4.2, 2.6), subplot_kw={"aspect": "equal"})

    bands = [(0.0, 0.34, "#16A34A"), (0.34, 0.67, "#D97706"), (0.67, 1.0, "#DC2626")]
    for lo, hi, color in bands:
        theta1 = 180 - hi * 180
        theta2 = 180 - lo * 180
        wedge = mpatches.Wedge(
            (0, 0), 1.0, theta1, theta2, width=0.32,
            facecolor=color, edgecolor="white", linewidth=1.5,
        )
        ax.add_patch(wedge)

    # Needle pointing at the predicted probability
    theta = math.radians(180 - probability * 180)
    x, y = 0.82 * math.cos(theta), 0.82 * math.sin(theta)
    ax.plot([0, x], [0, y], color="#1E293B", linewidth=3, solid_capstyle="round")
    ax.add_patch(mpatches.Circle((0, 0), 0.045, color="#1E293B", zorder=5))

    risk_hex = RISK_HEX.get(risk_level, "#1E293B")
    ax.text(0, -0.32, f"{probability * 100:.1f}%", ha="center", va="center",
            fontsize=22, fontweight="bold", color=risk_hex)
    ax.text(0, -0.55, "Predicted Diabetes Probability", ha="center", va="center",
            fontsize=9, color="#64748B")

    ax.set_xlim(-1.15, 1.15)
    ax.set_ylim(-0.65, 1.15)
    ax.axis("off")
    return fig


def _plot_feature_profile(inputs: dict[str, float]):
    """Horizontal bar chart showing where each of the patient's 8 input
    values falls within its clinically plausible range (0 = minimum,
    1 = maximum), so a reviewer can see at a glance which readings are
    elevated relative to the accepted range."""
    fields = list(FEATURE_RANGES.keys())
    labels = [FEATURE_RANGES[f][2] for f in fields]

    fractions = []
    for field in fields:
        lo, hi, _ = FEATURE_RANGES[field]
        value = inputs.get(field, lo)
        frac = (value - lo) / (hi - lo) if hi > lo else 0.0
        fractions.append(max(0.0, min(1.0, frac)))

    fig, ax = plt.subplots(figsize=(6.2, 3.4))
    y_pos = np.arange(len(fields))
    bar_colors = ["#DC2626" if f >= 0.7 else "#3B82F6" for f in fractions]
    ax.barh(y_pos, fractions, color=bar_colors, height=0.6, zorder=3)

    ax.set_yticks(y_pos)
    ax.set_yticklabels(labels, fontsize=8.5)
    ax.invert_yaxis()
    ax.set_xlim(0, 1.12)
    ax.set_xlabel("Position within clinical range (0 = min, 1 = max)", fontsize=8)
    ax.axvline(1.0, color="#CBD5E1", linewidth=0.8, zorder=1)
    ax.grid(axis="x", color="#E2E8F0", linewidth=0.6, zorder=0)
    for spine in ("top", "right", "left"):
        ax.spines[spine].set_visible(False)

    for i, field in enumerate(fields):
        value = inputs.get(field, "-")
        ax.text(min(fractions[i] + 0.03, 1.0), i, f"{value:g}" if isinstance(value, (int, float)) else str(value),
                va="center", fontsize=7.5, color="#1E293B")

    fig.tight_layout()
    return fig



def _styles() -> dict:
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "ReportTitle", parent=base["Title"], textColor=BRAND_COLOR, fontSize=20,
        ),
        "subtitle": ParagraphStyle(
            "ReportSubtitle", parent=base["Normal"], textColor=colors.HexColor("#64748B"),
            fontSize=10, spaceAfter=16,
        ),
        "heading": ParagraphStyle(
            "ReportHeading", parent=base["Heading2"], textColor=colors.HexColor("#1E293B"),
            spaceBefore=12, spaceAfter=6,
        ),
        "body": base["Normal"],
        "disclaimer": ParagraphStyle(
            "Disclaimer", parent=base["Normal"], fontSize=8,
            textColor=colors.HexColor("#94A3B8"), spaceBefore=20,
        ),
    }


def _patient_info_table(patient_profile: dict | None) -> Table | None:
    """Build the "Patient Information" table shown at the top of a report,
    before the prediction/clinical details, when a profile is available.
    Returns None if no profile was supplied (e.g. the user hasn't
    completed their patient profile yet) so callers can skip the section
    entirely rather than rendering a table full of placeholders."""
    if not patient_profile:
        return None

    rows = [
        ["Field", "Value"],
        ["Patient Name", str(patient_profile.get("patient_name", "-"))],
        ["Gender", str(patient_profile.get("gender", "-"))],
        ["Age", str(patient_profile.get("age", "-"))],
        ["Date of Birth", str(patient_profile.get("date_of_birth", "-"))],
        ["Blood Group", str(patient_profile.get("blood_group", "-"))],
        ["Phone Number", str(patient_profile.get("phone", "-"))],
        ["BMI", str(patient_profile.get("bmi", "-"))],
        ["Height", f"{patient_profile.get('height', '-')} cm"],
        ["Weight", f"{patient_profile.get('weight', '-')} kg"],
        ["Emergency Contact",
         f"{patient_profile.get('emergency_contact_name', '-')} "
         f"({patient_profile.get('emergency_contact_number', '-')})"],
    ]
    table = Table(rows, colWidths=[2.2 * inch, 3.3 * inch])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_COLOR),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F4F6FB")]),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return table


def generate_prediction_report(
    username: str,
    inputs: dict[str, float],
    prediction_label: str,
    probability: float,
    risk_level: str,
    suggestions: list[str],
    out_path: Path,
    patient_profile: dict | None = None,
) -> Path:
    """Render a single prediction result as a one-page PDF report.

    `patient_profile`, if given, is a dict shaped like
    `app.profile.PatientProfile.report_dict()` -- when provided, a "Patient
    Information" section is rendered before the clinical inputs.
    """
    styles = _styles()
    doc = SimpleDocTemplate(
        str(out_path), pagesize=letter,
        topMargin=0.6 * inch, bottomMargin=0.6 * inch,
        leftMargin=0.7 * inch, rightMargin=0.7 * inch,
    )
    story = []

    story.append(Paragraph("Diabetes Risk Prediction Report", styles["title"]))
    story.append(Paragraph(
        f"Patient: {username}  |  Generated: "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        styles["subtitle"],
    ))

    patient_table = _patient_info_table(patient_profile)
    if patient_table is not None:
        story.append(Paragraph("Patient Information", styles["heading"]))
        story.append(patient_table)

    story.append(Paragraph("Clinical Inputs", styles["heading"]))
    input_rows = [["Field", "Value"]]
    for field, (_lo, _hi, label) in FEATURE_RANGES.items():
        input_rows.append([label, str(inputs.get(field, "-"))])

    input_table = Table(input_rows, colWidths=[3.2 * inch, 2.3 * inch])
    input_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_COLOR),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F4F6FB")]),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(input_table)

    story.append(Paragraph("Prediction Result", styles["heading"]))
    risk_color = RISK_COLOR_MAP.get(risk_level, colors.grey)
    result_rows = [
        ["Prediction", prediction_label],
        ["Probability", f"{probability * 100:.1f}%"],
        ["Risk Level", risk_level],
    ]
    result_table = Table(result_rows, colWidths=[3.2 * inch, 2.3 * inch])
    result_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("BACKGROUND", (1, 2), (1, 2), risk_color),
        ("TEXTCOLOR", (1, 2), (1, 2), colors.white),
        ("FONTNAME", (1, 2), (1, 2), "Helvetica-Bold"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(result_table)

    story.append(Paragraph("Prediction Visualization", styles["heading"]))
    gauge_fig = _plot_probability_gauge(probability, risk_level)
    story.append(_fig_to_flowable(gauge_fig, target_width=3.4 * inch))
    story.append(Spacer(1, 6))

    profile_fig = _plot_feature_profile(inputs)
    story.append(_fig_to_flowable(profile_fig, target_width=5.6 * inch))

    story.append(Paragraph("Suggestions", styles["heading"]))
    for tip in suggestions:
        story.append(Paragraph(f"&bull; {tip}", styles["body"]))

    story.append(Spacer(1, 12))
    story.append(Paragraph(DISCLAIMER, styles["disclaimer"]))

    doc.build(story)
    logger.info("Generated prediction PDF report for %s at %s", username, out_path)
    return out_path


def generate_history_report(
    username: str,
    history_rows: list,
    out_path: Path,
    patient_profile: dict | None = None,
) -> Path:
    """Render a user's full prediction history as a tabular PDF report."""
    styles = _styles()
    doc = SimpleDocTemplate(
        str(out_path), pagesize=letter,
        topMargin=0.6 * inch, bottomMargin=0.6 * inch,
        leftMargin=0.5 * inch, rightMargin=0.5 * inch,
    )
    story = []

    story.append(Paragraph("Diabetes Prediction History Report", styles["title"]))
    story.append(Paragraph(
        f"Patient: {username}  |  Generated: "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  |  "
        f"Total records: {len(history_rows)}",
        styles["subtitle"],
    ))

    patient_table = _patient_info_table(patient_profile)
    if patient_table is not None:
        story.append(Paragraph("Patient Information", styles["heading"]))
        story.append(patient_table)
        story.append(Spacer(1, 8))

    if not history_rows:
        story.append(Paragraph("No prediction history available.", styles["body"]))
    else:
        header = ["Date", "Prediction", "Probability", "Risk", "Glucose", "BMI", "Age"]
        rows = [header]
        for row in history_rows:
            rows.append([
                row["created_at"],
                row["prediction"],
                f"{row['probability'] * 100:.1f}%",
                row["risk_level"],
                str(row["glucose"]),
                str(row["bmi"]),
                str(row["age"]),
            ])

        table = Table(rows, repeatRows=1, colWidths=[
            1.3 * inch, 0.9 * inch, 0.8 * inch, 0.6 * inch, 0.7 * inch, 0.6 * inch, 0.5 * inch,
        ])
        style_commands = [
            ("BACKGROUND", (0, 0), (-1, 0), BRAND_COLOR),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#E2E8F0")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F4F6FB")]),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]
        for i, row in enumerate(history_rows, start=1):
            risk_color = RISK_COLOR_MAP.get(row["risk_level"])
            if risk_color:
                style_commands.append(("TEXTCOLOR", (3, i), (3, i), risk_color))
                style_commands.append(("FONTNAME", (3, i), (3, i), "Helvetica-Bold"))
        table.setStyle(TableStyle(style_commands))
        story.append(table)

    story.append(Spacer(1, 12))
    story.append(Paragraph(DISCLAIMER, styles["disclaimer"]))

    doc.build(story)
    logger.info("Generated history PDF report for %s (%d records) at %s",
                username, len(history_rows), out_path)
    return out_path
